-- Elmira/Display/TextureLibrary.lua — the visual texture library (AT4-D2).
--
-- PURE DATA AND PURE LOOKUPS. No frames, no WoW API, no `ns` reads: this file answers "which
-- textures may a player pick from, and what are they called", and nothing else. Who draws the grid
-- is Options/TexturePickerWidget.lua's business; whether WeakAuras is installed is the adapter's
-- (`Adapter.addonLoaded`), and arrives here as a PREDICATE rather than being asked for, which is
-- what keeps this file testable on its own and free of the client. The one category that is not
-- here is LibSharedMedia's, which is live rather than fixed and is assembled by
-- `Display/Textures.libraryGroups` from the library the player actually runs.
--
-- ------------------------------------------------------------------ where these paths come from
--
-- LICENCE FIRST (owner's decision, 2026-09-11). Elmira is MIT; WeakAuras and PowerAuras are GPL.
-- Not one of their files is copied into this repository and none ever will be: what is listed below
-- is a PATH, and a path is a fact about the client's own file system in the same way an item's
-- inventory slot is a fact about the item. Every WeakAuras or PowerAuras path is offered ONLY on a
-- character that already has WeakAuras installed -- we point at the player's own copy, we never
-- ship one. Every DISPLAY NAME here is ours: generated by `nameFromPath` below from the path's last
-- segment, or written here beside a numeric id. No name string was copied from anybody's list.
--
-- THE BLIZZARD ENTRIES ARE FILE IDs, not paths, and that is the client's doing rather than a choice
-- made here: Blizzard's own art is addressable by numeric file id, the 1.15 client accepts one
-- where it accepts a path (this is how every texture picker on this install feeds `SetTexture`),
-- and the ids below are exactly the ones that resolve on CLASSIC ERA.
--
-- THERE IS NO "BLIZZARD ALERTS" CATEGORY, and its absence is deliberate: the proc-overlay family
-- (the biggest and prettiest set on retail) is not in this client's data at all. WeakAuras on this
-- very install drops the whole group on Classic Era, along with 17 beams, 9 icons and 9 runes it
-- keeps elsewhere; those are dropped here too. Listing them would put ~120 empty cells in the
-- picker, which is this addon's characteristic defect -- something that looks like a feature and
-- draws nothing. Read off the live install 2026-09-11; no code and no name string came with them.
