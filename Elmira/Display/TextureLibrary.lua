-- TextureLibrary.groups(isLoaded) -> every declared category, this character's own marked
--
-- `isLoaded(addonName)` is the caller's predicate -- `Display/Textures.addonLoaded` in the addon, a
-- plain function in a spec. TX1-D6 (owner): a category whose addon is not loaded is no longer
-- DROPPED -- it is handed back with `unavailable = <addon name>` instead, so the picker's Category
-- dropdown can still LIST it, greyed out with a reason, rather than making it look as if WeakAuras
-- simply has no shapes. A group that is available is the SAME table as in `GROUPS` (nothing here
-- ever copies a texture list); one that is not is a fresh table borrowing that same `textures`
-- field, so the shared definition itself never carries this session's own WeakAuras state.
function TextureLibrary.groups(isLoaded)
  local out = {}
  for _, group in ipairs(TextureLibrary.GROUPS) do
    if not group.requires or (isLoaded and isLoaded(group.requires) == true) then
      out[#out + 1] = group
    else
      out[#out + 1] = {
        key = group.key, name = group.name, textures = group.textures,
        requires = group.requires, unavailable = group.requires,
      }
    end
  end
  return out
end

-- TextureLibrary.requires(path) -> the addon this path needs, or nil
--
-- Pure prefix test, not a lookup in the lists above: a path a player typed, or one stored before
-- they uninstalled WeakAuras, is exactly the case AT4-D3 is about and it may be in no category at
-- all. Case-insensitive, because `Interface\AddOns\…` and `Interface\Addons\…` are the same folder
-- to the client and both spellings are in circulation (WeakAuras itself uses both).
function TextureLibrary.requires(path)
  local lowered = tostring(path or ""):lower():gsub("/", "\\")
  if lowered:find("interface\\addons\\weakauras\\", 1, true) == 1 then return WEAKAURAS end
  return nil -- mutants: equivalent the last statement of a function; Lua returns nil either way
end

-- TextureLibrary.drawable(path) -> what `SetTexture` wants
--
-- A Blizzard entry is a numeric FILE ID and has to arrive at the client as a number; a path arrives
-- as a string. One conversion, in one place, so the indicator and the picker can never disagree
-- about which of the two a stored value is -- an id passed as a string draws nothing at all, which
-- is the exact failure this channel already falls back to the ring for.
function TextureLibrary.drawable(path)
  return tonumber(path) or path
end

-- TextureLibrary.matches(name, needle) -> does this entry answer the picker's search box
--
-- Plain case-insensitive substring, never a pattern: a player typing `circle_` is typing part of a
-- file name, and `-` and `%` in a Lua pattern would either error or quietly match nothing.
function TextureLibrary.matches(name, needle)
  if needle == nil or needle == "" then return true end
  return tostring(name or ""):lower():find(tostring(needle):lower(), 1, true) ~= nil
end

