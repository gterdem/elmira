-- TextureLibrary.nameFromPath(path) -> a human name
--
-- OUR name for a file, built from the file's own last segment: extension dropped, `_`/`-` turned
-- into spaces, run-together words split at a lower-to-upper or letter-to-digit boundary, each word
-- given a capital -- so `Circle_AlphaGradient_In.tga` reads "Circle Alpha Gradient In" and
-- `PVP-Banner-Emblem-7` keeps its shouted PVP. A generated file name, never translated prose:
-- there is no locale in which `square_border_5px.tga` is a different file.
function TextureLibrary.nameFromPath(path)
  local tail = tostring(path or ""):match("([^\\/]+)$") or ""
  tail = tail:gsub("%.%a+$", "")
  tail = tail:gsub("[_%-]", " ")
  tail = tail:gsub("(%l)(%u)", "%1 %2")
  tail = tail:gsub("(%a)(%d)", "%1 %2")
  tail = tail:gsub("%s+", " ")
  tail = tail:gsub("^%s*(.-)%s*$", "%1")
  return (tail:gsub("%S+", function(word)
    local capitalised = word:gsub("^%l", string.upper)
    return capitalised
  end))
end

-- mutants: the return below is equivalent -- `add` is local (not exported); every caller uses it
-- only for the side effect on `out`, and none reads this return value.
local function add(out, path, name)
  out[#out + 1] = { path = path, name = name or TextureLibrary.nameFromPath(path) }
  return out -- mutants: equivalent see above
end

-- A run of numeric file ids under one heading. The id IS the whole path, so there is no segment to
-- generate a name from -- the category's own noun supplies the word and the id tells two of them
-- apart, which is all a name has to do beside a preview of the thing itself.
local function addIDs(out, noun, ids)
  for _, id in ipairs(ids) do add(out, id, noun .. " " .. id) end
  return out
end

